"""Generate src/tables.mach from the reference tables.c.

The three trigonometry tables are data, not code, so they are carried over
mechanically rather than retyped. Run from products/doom.
"""
import io
import re

src = io.open("ref/DOOM/linuxdoom-1.10/tables.c", encoding="latin-1").read()
src = re.sub(r"//[^\n]*", "", src)


def table(name):
    body = re.search(name + r"\[[^\]]*\]\s*=\s*\{(.*?)\};", src, re.S).group(1)
    return re.findall(r"-?(?:0x[0-9a-fA-F]+|\d+)", body)


def literal(name, kind, values, per_line):
    lines = ["pub val %s: [%d]%s = [%d]%s{" % (name, len(values), kind, len(values), kind)]
    for i in range(0, len(values), per_line):
        lines.append("    " + ", ".join(values[i:i + per_line]) + ",")
    lines[-1] = lines[-1].rstrip(",")
    lines.append("};")
    return "\n".join(lines)


tangent, sine, angle = table("finetangent"), table("finesine"), table("tantoangle")
assert (len(tangent), len(sine), len(angle)) == (4096, 10240, 2049)

out = """# the trigonometry tables: sine, tangent and arctangent at fixed resolutions
#
# Generated by harness/gentables.py from the tables in tables.c. Do not edit.
#
# An angle is a full 32-bit turn: 0x40000000 is 90 degrees, and overflow is
# rotation. A "fine" angle is its top 13 bits, an index into these tables.

pub val FINEANGLES: i32 = 8192;
pub val FINEMASK:   i32 = 8191;

# shift an angle right by this to get a fine angle
pub val ANGLETOFINESHIFT: u32 = 19;

pub val ANG45:  u32 = 0x20000000;
pub val ANG90:  u32 = 0x40000000;
pub val ANG180: u32 = 0x80000000;
pub val ANG270: u32 = 0xc0000000;

pub val SLOPERANGE: u32 = 2048;
pub val DBITS:      i32 = 5;

# index of the cosine within FINESINE: a quarter turn ahead
pub val COSINE: i32 = 2048;

# the slope of a line as an index into TANTOANGLE
# ---
# num: the shorter leg
# den: the longer leg
# ret: 0 to SLOPERANGE
pub fun slope_div(num: u32, den: u32) u32 {
    if (den < 512) { ret SLOPERANGE; }
    val ans: u32 = (num << 3) / (den >> 8);
    if (ans <= SLOPERANGE) { ret ans; }
    ret SLOPERANGE;
}

# tangent of each fine angle over half a turn, from -90 to +90 degrees
%s

# sine of each fine angle over a turn and a quarter, so that the cosine of any
# fine angle is FINESINE[COSINE + angle]
%s

# the angle whose tangent is index / SLOPERANGE, from 0 to 45 degrees
%s

test tables__known_entries {
    if (FINESINE[0] != 25 || FINESINE[2048] != 65535 || FINESINE[10239] != 65535) { ret 1; }
    if (FINETANGENT[0] != 0 - 170910304 || FINETANGENT[4095] != 170910304)        { ret 2; }
    if (TANTOANGLE[0] != 0 || TANTOANGLE[2048] != 0x20000000)                     { ret 3; }
    ret 0;
}

test slope_div__clamps {
    if (slope_div(100, 511) != 2048)         { ret 1; }
    if (slope_div(1 << 16, 2 << 16) != 1024) { ret 2; }
    if (slope_div(3 << 16, 1 << 16) != 2048) { ret 3; }
    ret 0;
}
""" % (literal("FINETANGENT", "i32", tangent, 8),
       literal("FINESINE", "i32", sine, 8),
       literal("TANTOANGLE", "u32", angle, 8))

io.open("src/tables.mach", "w", encoding="ascii", newline="\n").write(out)
print(sine[0], sine[2048], sine[10239], tangent[0], tangent[4095], angle[0], angle[2048])
