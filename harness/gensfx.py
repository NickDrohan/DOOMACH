"""Generate src/sfx.mach from the reference sounds.c.

The sound effect table is data: a lump name and a priority for each of the
effects that info.mach numbers. Run from the repository root.
"""
import io
import re

text = io.open("ref/DOOM/linuxdoom-1.10/sounds.c", encoding="latin-1").read()
text = re.sub(r"//[^\n]*", "", text)
body = text[text.index("sfxinfo_t S_sfx[]"):]
rows = re.findall(r'\{\s*"(\w+)"\s*,\s*(\w+)\s*,\s*(\d+)\s*,', body)
assert rows[0][0] == "none" and len(rows) > 100, len(rows)

out = ["""# the sound effects: the lump each is stored in and how readily it gives way
#
# Generated by harness/gensfx.py from sounds.c. Do not edit.
#
# An effect's lump is named DS followed by its name here. Its number is the
# SFX_* constant in info.mach. A lower priority number wins a channel from a
# higher one when all are busy.

pub val NUMSFX: i32 = %d;

# six characters per effect, zero padded
val NAMES: [%d]u8 = [%d]u8{""" % (len(rows), len(rows) * 6, len(rows) * 6)]
for i, (name, _, _) in enumerate(rows):
    padded = ["'%s'" % c.upper() for c in name] + ["0"] * (6 - len(name))
    out.append("    " + ", ".join(padded) + ("," if i + 1 < len(rows) else ""))
out.append("};")
out.append("")
out.append("val PRIORITY: [%d]i32 = [%d]i32{" % (len(rows), len(rows)))
for i in range(0, len(rows), 16):
    chunk = ", ".join(r[2] for r in rows[i:i + 16])
    out.append("    " + chunk + ("," if i + 16 < len(rows) else ""))
out.append("};")
out.append("""
# an effect's priority
pub fun priority(sfx: i32) i32 {
    ret PRIORITY[sfx];
}

# write an effect's lump name, DS and its name, into a buffer of nine bytes
pub fun lump_name(sfx: i32, out: *u8) {
    out[0] = 'D';
    out[1] = 'S';
    var k: i32 = 0;
    for (k < 6) {
        out[2 + k] = NAMES[sfx * 6 + k];
        k          = k + 1;
    }
    out[8] = 0;
}

test sfx__known_rows {
    var name: [9]u8;
    lump_name(1, ?name[0]);
    if (name[2] != 'P' || name[3] != 'I' || name[7] != 'L' || name[8] != 0) { ret 1; }
    if (priority(1) != 64 || priority(0) != 0)                              { ret 2; }
    ret 0;
}
""")
io.open("src/sfx.mach", "w", encoding="ascii", newline="\n").write("\n".join(out))
print(len(rows), "effects;", rows[1], rows[-1])
