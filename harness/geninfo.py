"""Generate src/info.mach from the reference info.h, info.c and sounds.h.

The state table, the object-type table and their enumerations are data: 967
states and 137 object types, each row a handful of numbers. They are carried
over mechanically rather than retyped. Run from the repository root.
"""
import io
import re

REF = "ref/DOOM/linuxdoom-1.10/"


def read(name):
    text = io.open(REF + name, encoding="latin-1").read().replace("\r", "")
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    return re.sub(r"//[^\n]*", "", text)


def enum(text, closing):
    """The names of the enum whose typedef ends with `closing`, in order."""
    end = text.index("} " + closing)
    start = text.rindex("{", 0, end)
    return [n.strip() for n in text[start + 1:end].split(",") if n.strip()]


info_h, info_c, sounds_h = read("info.h"), read("info.c"), read("sounds.h")

sprites = enum(info_h, "spritenum_t")
states = enum(info_h, "statenum_t")
types = enum(info_h, "mobjtype_t")
sfx = enum(sounds_h, "sfxenum_t")
assert sprites[-1] == "NUMSPRITES" and states[-1] == "NUMSTATES" and types[-1] == "NUMMOBJTYPES"

flags = dict(re.findall(r"(MF_\w+)\s*=\s*(\w+)", read("p_mobj.h")))
env = {name: i for names in (sprites, states, types, sfx) for i, name in enumerate(names)}
env.update({k: int(v, 0) for k, v in flags.items()})
env["FRACUNIT"] = 65536

body = info_c[info_c.index("state_t\tstates[NUMSTATES]"):]
state_rows = re.findall(r"\{(SPR_\w+),([^,]+),([^,]+),\{(\w+)\},(\w+),([^,]+),([^}]+)\}", body)
assert len(state_rows) == len(states) - 1, len(state_rows)

actions = ["NULL"]
for row in state_rows:
    if row[3] not in actions:
        actions.append(row[3])

mobj_body = info_c[info_c.index("mobjinfo_t mobjinfo[NUMMOBJTYPES]"):]
mobj_rows = re.findall(r"\{\s*//?[^\n]*\n?(.*?)\}", mobj_body, re.S)
mobj_rows = re.findall(r"\{([^{}]*)\}", mobj_body[mobj_body.index("{") + 1:])
assert len(mobj_rows) == len(types) - 1, len(mobj_rows)

FIELDS = ["doomednum", "spawnstate", "spawnhealth", "seestate", "seesound", "reactiontime",
          "attacksound", "painstate", "painchance", "painsound", "meleestate", "missilestate",
          "deathstate", "xdeathstate", "deathsound", "speed", "radius", "height", "mass",
          "damage", "activesound", "flags", "raisestate"]

out = []
emit = out.append
emit("""# the state table and the object-type table: what every thing in the game is,
# looks like and does next
#
# Generated by harness/geninfo.py from info.h, info.c and sounds.h. Do not edit.
#
# A state is one animation frame: a sprite, how long it lasts, an action to
# run on entering it, and the state that follows. An object type names the
# states it moves between (spawn, see, pain, melee, missile, death) with its
# size, speed, health and flags. The tables are flat arrays of i32, one row
# after another; the accessors below read a field of a row.
""")

emit("# sprites")
for i, name in enumerate(sprites):
    emit("pub val %s: i32 = %d;" % (name, i))
emit("\n# states")
for i, name in enumerate(states):
    emit("pub val %s: i32 = %d;" % (name, i))
emit("\n# object types")
for i, name in enumerate(types):
    emit("pub val %s: i32 = %d;" % (name, i))
emit("\n# sound effects")
for i, name in enumerate(sfx):
    emit("pub val %s: i32 = %d;" % (name.upper(), i))
emit("\n# actions a state can run; A_NULL is none")
for i, name in enumerate(actions):
    emit("pub val %s: i32 = %d;" % ("A_NULL" if name == "NULL" else name.upper(), i))

emit("\n# fields of an object type's row")
for i, name in enumerate(FIELDS):
    emit("pub val MI_%s: i32 = %d;" % (name.upper(), i))

emit("\n# the four letters of each sprite's lump names")
letters = re.search(r"sprnames\[NUMSPRITES\]\s*=\s*\{(.*?)\};", info_c, re.S).group(1)
names = re.findall(r'"(\w{4})"', letters)
assert len(names) == len(sprites) - 1
emit("pub val SPRNAMES: [%d]u8 = [%d]u8{" % (len(names) * 4, len(names) * 4))
for i in range(0, len(names), 8):
    row = ", ".join("'%s'" % c for n in names[i:i + 8] for c in n)
    emit("    " + row + ("," if i + 8 < len(names) else ""))
emit("};")

emit("\n# per state: sprite, frame, tics, action, next state, misc1, misc2")
emit("val STATES: [%d]i32 = [%d]i32{" % (len(state_rows) * 7, len(state_rows) * 7))
for i, row in enumerate(state_rows):
    action = actions.index(row[3])
    values = [eval(row[0], env), eval(row[1], env), eval(row[2], env), action,
              eval(row[4], env), eval(row[5], env), eval(row[6], env)]
    emit("    " + ", ".join(str(v) for v in values) + ("," if i + 1 < len(state_rows) else ""))
emit("};")

emit("\n# per object type: the %d fields named MI_* above" % len(FIELDS))
emit("val MOBJINFO: [%d]i32 = [%d]i32{" % (len(mobj_rows) * len(FIELDS), len(mobj_rows) * len(FIELDS)))
for i, row in enumerate(mobj_rows):
    values = [eval(v.strip(), env) for v in row.split(",") if v.strip()]
    assert len(values) == len(FIELDS), (i, len(values))
    emit("    " + ", ".join(str(v) for v in values) + ("," if i + 1 < len(mobj_rows) else ""))
emit("};")

emit("""
pub fun st_sprite(s: i32) i32 {
    ret STATES[s * 7];
}

pub fun st_frame(s: i32) i32 {
    ret STATES[s * 7 + 1];
}

pub fun st_tics(s: i32) i32 {
    ret STATES[s * 7 + 2];
}

pub fun st_action(s: i32) i32 {
    ret STATES[s * 7 + 3];
}

pub fun st_next(s: i32) i32 {
    ret STATES[s * 7 + 4];
}

pub fun st_misc1(s: i32) i32 {
    ret STATES[s * 7 + 5];
}

pub fun st_misc2(s: i32) i32 {
    ret STATES[s * 7 + 6];
}

# a field of an object type
# ---
# kind:  MT_* object type
# field: MI_* field
pub fun mi(kind: i32, field: i32) i32 {
    ret MOBJINFO[kind * %d + field];
}

test info__known_rows {
    if (NUMSTATES != 967 || NUMMOBJTYPES != 137 || NUMSPRITES != 138) { ret 1; }
    if (st_sprite(S_PLAY) != SPR_PLAY || st_tics(S_PLAY) != -1)       { ret 2; }
    if (st_action(S_PUNCH) != A_WEAPONREADY || st_next(S_PUNCH) != S_PUNCH) { ret 3; }
    if (mi(MT_PLAYER, MI_SPAWNHEALTH) != 100 || mi(MT_PLAYER, MI_RADIUS) != 16 * 65536) { ret 4; }
    if (mi(MT_POSSESSED, MI_DOOMEDNUM) != 3004 || mi(MT_TROOP, MI_DOOMEDNUM) != 3001)   { ret 5; }
    if (mi(MT_BARREL, MI_DEATHSTATE) != S_BEXP)                        { ret 6; }
    ret 0;
}
""" % len(FIELDS))

io.open("src/info.mach", "w", encoding="ascii", newline="\n").write("\n".join(out))
print(len(sprites) - 1, "sprites", len(state_rows), "states", len(mobj_rows), "types",
      len(sfx), "sounds", len(actions), "actions")
